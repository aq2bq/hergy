// build.js makes internal/web/static/vendor/preact.js: one ESM file holding
// preact, htm and @preact/signals (webui-preact-design 3 章).
//
//	go run ./tools/check vendor           check the committed file is this
//	go run ./tools/check vendor -write    write it again
//
// The versions come from tools/webvendor/package.json through bun.lock (both
// exact: no ^ or ~), never from the network at run time: what the screens
// import is decided by entry.js and nothing else. Bun is the pinned one
// tools/check puts in .bin/, so the output is the same on a laptop and in CI.
//
// The file is not minified: a person reads and reviews what the WebUI runs, and
// a dependency update's diff stays readable.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const here = import.meta.dir;
const out = join(here, '..', '..', 'internal', 'web', 'static', 'vendor', 'preact.js');

const built = await Bun.build({
  entrypoints: [join(here, 'entry.js')],
  format: 'esm',
  target: 'browser',
  minify: false,
});
if (!built.success) {
  for (const log of built.logs) console.error(log);
  process.exit(1);
}
const code = (await built.outputs[0].text()).trimEnd();

// The bundle names the file each module came from, so the packages it holds are
// read from the output itself: a package added to entry.js is listed here
// without this file being touched.
const packages = [];
for (const line of code.split('\n')) {
  const m = /^\/\/ node_modules\/((?:@[^/]+\/)?[^/]+)\//.exec(line);
  if (!m) continue;
  if (!packages.some((p) => p.name === m[1])) packages.push({ name: m[1] });
}
if (!packages.length) {
  console.error('build: the bundle names no package; refusing to write a file with no version or licence');
  process.exit(1);
}
for (const p of packages) {
  const meta = JSON.parse(readFileSync(join(here, 'node_modules', p.name, 'package.json'), 'utf8'));
  p.version = meta.version;
  p.license = meta.license;
  p.text = readFileSync(join(here, 'node_modules', p.name, 'LICENSE'), 'utf8').trimEnd();
}

const note = (s) => s.split('\n').map((l) => (l === '' ? '//' : '// ' + l)).join('\n');

const head = [
  '// Generated by tools/webvendor/build.js — do not edit by hand.',
  '//',
  '//   go run ./tools/check vendor           check this file is what the sources make',
  '//   go run ./tools/check vendor -write    write it again',
  '//',
  '// The versions are pinned in tools/webvendor/package.json (and bun.lock), and',
  '// the screens import these packages only through this file (webui-preact-design',
  '// 3 章). The licences, in full, are at the end of this file.',
  '//',
  ...packages.map((p) => `//   ${p.name} ${p.version} — ${p.license}`),
].join('\n');

const tail = [
  '',
  '// ---- licences ---------------------------------------------------------',
  ...packages.map((p) => ['//', `// ${p.name} ${p.version} — ${p.license}`, '//', note(p.text)].join('\n')),
].join('\n');

const file = `${head}\n\n${code}\n${tail}\n`;

// BUN_BUILD_OUT is where tools/check vendor puts the file it compares: the gate
// writes nothing itself unless it was told to.
const where = process.env.BUN_BUILD_OUT || out;
await Bun.write(where, file);
console.error(`build: wrote ${file.length} bytes to ${where}`);
