package words

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"strings"
)

// Generated returns deterministic artifacts. The caller compares or writes them.
func Generated() (map[string][]byte, error) {
	goTerms, err := generateGoTerms()
	if err != nil {
		return nil, err
	}
	tsTerms, err := generateTSTerms()
	if err != nil {
		return nil, err
	}
	return map[string][]byte{
		"internal/words/terms_generated.go":       goTerms,
		"internal/web/src/lib/terms.generated.ts": tsTerms,
	}, nil
}

func termName(id TermID) string {
	var b strings.Builder
	for part := range strings.SplitSeq(string(id), "-") {
		b.WriteString(strings.ToUpper(part[:1]) + part[1:])
	}
	return b.String()
}

func generateGoTerms() ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by go run ./tools/check words -write; DO NOT EDIT.\npackage words\n\nconst (\n")
	for _, t := range terms {
		fmt.Fprintf(&b, "Term%s TermID = %q\n", termName(t.ID), t.ID)
	}
	b.WriteString(")\n")
	return format.Source(b.Bytes())
}

func generateTSTerms() ([]byte, error) {
	table := map[TermID]map[string]string{}
	for _, t := range terms {
		table[t.ID] = map[string]string{"en": t.English, "ja": t.Japanese}
	}
	raw, err := json.MarshalIndent(table, "", "  ")
	if err != nil {
		return nil, err
	}
	return []byte("// Code generated by go run ./tools/check words -write; DO NOT EDIT.\nexport const terms = " + string(raw) + " as const;\nexport type TermID = keyof typeof terms;\nexport function term(id: TermID, lang: \"en\" | \"ja\" = \"ja\"): string { return terms[id][lang]; }\n"), nil
}
